/*
 * export_annotations.groovy -- back up every annotation of the current image as GeoJSON.
 *
 * Detections are NOT exported (v3 replaces every cell). Two files per image:
 *   <out>/annotations_all/<tag>.geojson     every annotation: class, name, measurements, object ID
 *   <out>/manual_annotations/<tag>.geojson  only classes the pipeline does not regenerate
 *                                           (Tissue, pLN, and anything hand-drawn)
 * plus <out>/manual_annotations/<tag>.json, a sentinel with per-class counts. The runner
 * checks the sentinel because headless QuPath exits 0 even when a script throws.
 *
 * Read-only: nothing is saved. Headless:
 *   QuPath script -p <project> -i "<image name>" -a <out> export_annotations.groovy
 */

import qupath.lib.io.GsonTools   // groovy-json is not bundled with QuPath 0.7

def outRoot = (binding.hasVariable('args') && args && args.length > 0) ? args[0] :
        '/home/smith6jt/IO60panc2nd/results/v3'
// Regenerated by the v3 pipeline (scripts 1, 4, 7 and the retired Gal3 density-map helper).
def DERIVED = ['Islet', 'IsletExpanded', 'EndocrineCluster', 'EndocrineSingle',
               'Nerve', 'Blood_vessel', 'Lymphatic', 'Other: Gal3Norm'] as Set

def entry = getProjectEntry()
def imageName = entry?.getImageName() ?: getCurrentServer()?.getMetadata()?.getName()
def tag = imageName.replaceAll(/[^A-Za-z0-9._-]+/, '_')

def anns = getAnnotationObjects()
def clsOf = { o -> o.getPathClass()?.toString() ?: 'Unclassified' }
def manual = anns.findAll { !(clsOf(it) in DERIVED) }

def allDir = new File(outRoot, 'annotations_all'); allDir.mkdirs()
def manDir = new File(outRoot, 'manual_annotations'); manDir.mkdirs()
def allFile = new File(allDir, tag + '.geojson')
def manFile = new File(manDir, tag + '.geojson')

if (!anns.isEmpty())
    exportObjectsToGeoJson(anns, allFile.getAbsolutePath(), 'FEATURE_COLLECTION')
if (!manual.isEmpty())
    exportObjectsToGeoJson(manual, manFile.getAbsolutePath(), 'FEATURE_COLLECTION')

def sentinel = [
        image              : imageName,
        entry_id           : entry?.getID(),
        n_annotations      : anns.size(),
        n_manual           : manual.size(),
        class_counts       : anns.countBy { clsOf(it) },
        manual_class_counts: manual.countBy { clsOf(it) },
        n_detections       : getDetectionObjects().size(),
        all_geojson        : anns.isEmpty() ? null : allFile.getAbsolutePath(),
        manual_geojson     : manual.isEmpty() ? null : manFile.getAbsolutePath(),
        exported_at        : java.time.OffsetDateTime.now().toString(),   // groovy-dateutil not bundled
]
new File(manDir, tag + '.json').text = GsonTools.getInstance(true).toJson(sentinel)
println "[export_annotations] ${imageName}: ${anns.size()} annotations (${manual.size()} manual) " +
        "${sentinel.manual_class_counts}"
